import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { extractFile, listPackage } from '@electron/asar';
const root = path.dirname(fileURLToPath(import.meta.url));
const directory = path.resolve(process.argv[2] || path.join(root, 'out/Jane Companion-win32-x64'));
for (const name of ['Jane Companion.exe', 'resources/app.asar', 'resources.pak', 'icudtl.dat', 'ffmpeg.dll', 'LICENSE', 'LICENSES.chromium.html', 'locales/zh-CN.pak']) assert.ok(fs.statSync(path.join(directory, name)).size > 0, name);
assert.ok(['使用说明.txt', 'README.txt'].some(name => fs.existsSync(path.join(directory, name)) && fs.statSync(path.join(directory, name)).size > 0), 'usage instructions');
const exe = fs.readFileSync(path.join(directory, 'Jane Companion.exe'));
assert.equal(exe.subarray(0, 2).toString(), 'MZ');
const pe = exe.readUInt32LE(0x3c);
assert.equal(exe.readUInt32LE(pe), 0x00004550); assert.equal(exe.readUInt16LE(pe + 4), 0x8664, 'Windows x64 executable');
const archive = path.join(directory, 'resources/app.asar');
const approved = JSON.parse(fs.readFileSync(path.join(root, 'artwork-manifest.json')));
const manifest = JSON.parse(extractFile(archive, 'assets/manifest.json'));
assert.deepEqual(manifest, approved);
assert.equal(listPackage(archive).filter(name => /\/assets\/png\/.*\.png$/.test(name)).length, 25);
for (const image of manifest.images) assert.equal(createHash('sha256').update(extractFile(archive, 'assets/' + image.file)).digest('hex'), image.sha256, image.id);
for (const name of ['main.cjs', 'preload.cjs', 'policy.cjs', 'program-launcher.cjs', 'offline.html', 'offline.js']) assert.ok(extractFile(archive, name).equals(fs.readFileSync(path.join(root, name))), name + ' is current');
assert.ok(extractFile(archive, 'offline.css').equals(fs.readFileSync(path.join(root, '../jane-companion.css'))));
const pkg = JSON.parse(extractFile(archive, 'package.json'));
console.log(JSON.stringify({ platform: 'win32-x64', version: pkg.version, approvedImages: 25, nativeSource: 'matches', runtime: 'complete', signed: false }));
